		-- 	-- AND C.GENERICATTRIBUTE1 = '000042784650000000000'
		-- 	GROUP BY C.GENERICATTRIBUTE4,H.CONTEO,C.GENERICATTRIBUTE1,S.LINENUMBER,S.SUBLINENUMBER,E.EVENTTYPEID
		-- 	ORDER BY SUMA DESC;

		TEMP_NUEVO_CALCULO =
			SELECT C.GENERICATTRIBUTE4 POSITIONNAME,H.CONTEO,C.GENERICATTRIBUTE1 POLIZA,S.LINENUMBER,S.SUBLINENUMBER,E.EVENTTYPEID
			,SUM(C.PREADJUSTEDVALUE) SUMA
			,ROW_NUMBER() OVER (PARTITION BY C.GENERICATTRIBUTE4 ORDER BY SUM(C.PREADJUSTEDVALUE) DESC) AS RN
			FROM CS_CREDIT C
			INNER JOIN CS_SALESTRANSACTION S ON C.SALESTRANSACTIONSEQ = S.SALESTRANSACTIONSEQ AND C.SALESORDERSEQ = S.SALESORDERSEQ AND S.PROCESSINGUNITSEQ = v_const_processingunitseq
