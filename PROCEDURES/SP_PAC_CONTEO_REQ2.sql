		-- FROM :TEMP_TRANSACTIONASSIGN T 
		-- INNER JOIN :TEMP_NUEVO_CALCULO C ON 1=1 
		-- AND T.ORDERID LIKE  '%'||SUBSTRING(C.POLIZA,0,16)||'%'
		-- AND T.LINENUMBER = C.LINENUMBER AND T.SUBLINENUMBER = C.SUBLINENUMBER AND T.EVENTTYPEID = C.EVENTTYPEID
		-- WHERE C.POSITIONNAME = '70341664M0000'
		-- ORDER BY C.RN DESC
		-- ;
	
		TEMP_MAX_RN = SELECT
		            POSITIONNAME,
		            MAX(RN) AS MAX_RN
		        FROM :TEMP_NUEVO_CALCULO
		        GROUP BY POSITIONNAME;
		
		 --SELECT * FROM :TEMP_MAX_RN;
		
		
		UPDATE T
		SET T.GENERICNUMBER2 = (CASE WHEN (MR.MAX_RN-C.CONTEO) >= C.RN  THEN 0 ELSE 1 END)
		FROM :TEMP_TRANSACTIONASSIGN T 
		INNER JOIN :TEMP_NUEVO_CALCULO C ON T.ORDERID LIKE  '%'||SUBSTRING(C.POLIZA,0,16)||'%'
			AND T.LINENUMBER = C.LINENUMBER AND T.SUBLINENUMBER = C.SUBLINENUMBER AND T.EVENTTYPEID = C.EVENTTYPEID
		INNER JOIN :TEMP_MAX_RN MR ON MR.POSITIONNAME = C.POSITIONNAME
		WHERE COALESCE(T.GENERICNUMBER2,0) <> 1 
		;
		
		


		
		SELECT 'FINAL',T.ORDERID,SUBSTRING(C.POLIZA,0,16) poliza,T.LINENUMBER,T.SUBLINENUMBER,T.EVENTTYPEID,T.POSITIONNAME,T.GENERICNUMBER2 KM,
		C.SUMA 
		,C.RN,C.CONTEO,R.MAX_RN
		FROM :TEMP_TRANSACTIONASSIGN T 
		INNER JOIN :TEMP_NUEVO_CALCULO C ON T.ORDERID LIKE  '%'||SUBSTRING(C.POLIZA,0,16)||'%'
			AND T.LINENUMBER = C.LINENUMBER AND T.SUBLINENUMBER = C.SUBLINENUMBER AND T.EVENTTYPEID = C.EVENTTYPEID
		INNER JOIN :TEMP_MAX_RN R ON R.POSITIONNAME = C.POSITIONNAME
		WHERE T.POSITIONNAME = '20816874B0000'
		ORDER BY POSITIONNAME,C.CONTEO DESC,T.POSITIONNAME, C.RN 
		;
		
		UPDATE EXT.OUT_BATCH_CONTROL SET STATUS = :v_const_out_batch_control_ok, TARGET_ROWS =v_num_rows, END_DATE = CURRENT_TIMESTAMP WHERE FILE_NAME = v_file_name AND ID_PROCESO = v_id_proceso;
		
		CALL EXT.LIB_GLOBAL:WRITE_LOG (v_permisos_log,proc_name, 'Fin procesamiento del fichero ' || i_file_name, v_log_count, v_id_proceso, 'info');
		
		
		
	END;
		
END;

