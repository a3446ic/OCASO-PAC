			INNER JOIN EXT.OUT_PAC_CONTEO_REQ2_FILE_HIST H ON H.POSITIONNAME = C.GENERICATTRIBUTE4
				AND H.CONTEO > 0 
				AND H.PERIODSEQ = v_periodseq
			WHERE 1=1
			AND C.PROCESSINGUNITSEQ = v_const_processingunitseq
			AND C.NAME = 'DC-O-GEN-Inspector-PrimaCorregida-998'
			AND C.GENERICATTRIBUTE4 = '20816874B0000'
			AND C.PERIODSEQ = v_periodseq 
			AND C.VALUE > 0 AND H.PERIODSEQ = v_periodseq
		--	GROUP BY C.GENERICATTRIBUTE4,H.CONTEO,C.GENERICATTRIBUTE1,S.LINENUMBER,S.SUBLINENUMBER,E.EVENTTYPEID
			ORDER BY C.GENERICATTRIBUTE4,C.VALUE DESC,RN
			
			;
		
			
			
		SELECT 'TEMP_NUEVO_CALCULO',* FROM :TEMP_NUEVO_CALCULO
		-- WHERE POSITIONNAME = '70341664M0000' 
		ORDER BY POSITIONNAME,suma desc;
		
		
